// Offline only: the catalog selects the vendored SVGs; no package or CDN.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
const base = new URL('../resources/icons/', import.meta.url);
const output = new URL('../public/assets/icons/', import.meta.url);
const shared = new URL('../public/assets/js/shared/', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('catalog.json', base), 'utf8'));
await mkdir(new URL('licenses/', output), { recursive: true });
await mkdir(shared, { recursive: true });
for (const library of new Set(Object.values(catalog.icons).map(entry => entry.library))) {
  await copyFile(new URL(`licenses/${library}.txt`, base), new URL(`licenses/${library}.txt`, output));
}
const body = svg => svg.replace(/<\?xml[^>]*>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const symbols = [];
for (const [name, entry] of Object.entries(catalog.icons)) {
  const svg = await readFile(new URL(`sources/${entry.library}/${entry.file}`, base), 'utf8');
  const scale = entry.scale ?? 1;
  const offset = 12 * (1 - scale);
  const contents = body(svg).replace(/(?:black|#000000|#000)/g, 'currentColor');
  const attrs = entry.library === 'papicons'
    ? `fill="currentColor" stroke="none" transform="translate(${offset} ${offset}) scale(${scale})"`
    : 'fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"';
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24"><g ${attrs}>${contents}</g></symbol>`);
}
const brand = await readFile(new URL('sources/braindump.svg', base), 'utf8');
symbols.push(`<symbol id="i-brain" viewBox="0 0 32 32"><g fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${body(brand)}</g></symbol>`);
await writeFile(new URL('sprite.svg', output), `<!-- Generated by scripts/build-icons.mjs. Licenses: ./licenses/ -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
await writeFile(new URL('icons.js', shared), `// Generated semantic icon registry. Edit resources/icons/catalog.json and run npm run icons:build.\nconst names = new Set(${JSON.stringify([...Object.keys(catalog.icons), 'brain'])});\nexport function icon(name) {\n  name = name.replace(/^i-/, '');\n  if (!names.has(name)) throw new Error('Icône inconnue : ' + name);\n  return '<svg class="icon" aria-hidden="true" focusable="false"><use href="/assets/icons/sprite.svg#i-' + name + '"/></svg>';\n}\n`);
console.log(`${symbols.length} symboles SVG locaux générés.`);
